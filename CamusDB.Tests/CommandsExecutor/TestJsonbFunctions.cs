        ("select k from jsonb_object_keys('{\"b\":1,\"a\":2,\"aa\":3}'::jsonb) k", "a\nb\naa"),
        ("select value::text from jsonb_array_elements('[1,\"two\",[3],null]'::jsonb)", "1\n\"two\"\n[3]\nnull"),
        ("select coalesce(value,'<NULL>') from jsonb_array_elements_text('[1,\"two\",[3],null]'::jsonb)", "1\ntwo\n[3]\n<NULL>"),
        ("select key from jsonb_each('[1]'::jsonb)", "ERROR: ERROR:  cannot call jsonb_each on a non-object"),
        ("select value from jsonb_array_elements('{\"a\":1}'::jsonb)", "ERROR: ERROR:  cannot extract elements from an object"),
    ];

    private static async Task<string> Run(CommandExecutor executor, DatabaseDescriptor db, string sql)
    {
        KvTransaction tx = await db.Transactions.BeginAsync();
        try
        {
            QuerySchemaHolder schema = new();
            (_, IAsyncEnumerable<QueryResultRow> cursor) = await executor.ExecuteSQLQuery(
                new ExecuteSQLTicket(tx, db.Name, sql, null), schemaOut: schema);
            List<QueryResultRow> rows = await cursor.ToListAsync();

            // The psql -At form: one line per row, columns joined by the unit separator.
            return string.Join("\n", rows.Select(row => string.Join("\u001f",
                schema.Schema.Select(column => Text(row.Row[column.RowKey])))));
        }
        finally
        {
            await db.Transactions.RollbackIfNotCompletedAsync(tx);
        }
    }

    private static string Text(ColumnValue value) => value.Type switch
    {
        ColumnType.Null => "",
        ColumnType.Jsonb => value.JsonValue!,
        ColumnType.Bool => value.BoolValue ? "true" : "false",
        ColumnType.Integer64 => value.LongValue.ToString(System.Globalization.CultureInfo.InvariantCulture),
        _ => value.StrValue ?? value.ToString(),
    };

    private static void Check(StringBuilder mismatches, ref int failures, string expression, string expected, string actual)
    {
        bool ok = expected.StartsWith("ERROR: ")
            ? actual.StartsWith("ERROR: ") && actual.Contains(expected["ERROR: ERROR:  ".Length..])
            : actual == expected;

        if (!ok)
        {
            failures++;
            mismatches.AppendLine($"{expression}\n    expected: {expected}\n    actual:   {actual}");
        }
    }

    [Test]
    [NonParallelizable]
    public async Task EveryScalarCase_MatchesPostgreSql()
    {
        (_, DatabaseDescriptor db, CommandExecutor executor) = await CreateDatabase();
        StringBuilder mismatches = new();
        int failures = 0;

        foreach ((string expression, string expected) in ScalarCases)
        {
            string actual;
            try
            {
                actual = await Run(executor, db, $"SELECT coalesce(({expression})::text, '<NULL>') AS r");
            }
            catch (CamusDBException ex)
            {
                actual = "ERROR: " + ex.Message;
            }

            Check(mismatches, ref failures, expression, expected, actual);
        }

        Assert.AreEqual(0, failures, $"{failures} of {ScalarCases.Length} cases differ from PostgreSQL:\n{mismatches}");
    }

