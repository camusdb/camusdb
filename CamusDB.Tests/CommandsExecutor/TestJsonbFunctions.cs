    [Test]
    [NonParallelizable]
    public async Task SetReturning_ColumnNamesFollowPostgreSql_AndTheAliasRenamesFromTheLeft()
    {
        (_, DatabaseDescriptor db, CommandExecutor executor) = await CreateDatabase();

        Assert.AreEqual("a\u001f1", await Run(executor, db, "SELECT e.key, e.value FROM jsonb_each('{\"a\": 1}') AS e"));
        Assert.AreEqual("a\u001f1", await Run(executor, db, "SELECT k, value FROM jsonb_each('{\"a\": 1}') AS e(k)"));
        Assert.AreEqual("a\u001f1", await Run(executor, db, "SELECT k, v FROM json_each_text('{\"a\": 1}') AS e(k, v)"));
        Assert.AreEqual("x", await Run(executor, db, "SELECT jsonb_object_keys FROM jsonb_object_keys('{\"x\": 0}')"));
        Assert.AreEqual("1\n2", await Run(executor, db, "SELECT value FROM jsonb_array_elements('[1, 2]')"));
        Assert.AreEqual("2", await Run(executor, db, "SELECT COUNT(*) AS c FROM jsonb_array_elements_text('[1, 2]')"));
        Assert.AreEqual("", await Run(executor, db, "SELECT key FROM jsonb_each(CAST(NULL AS jsonb))"));

        CamusDBException tooMany = Assert.ThrowsAsync<CamusDBException>(async () =>
            await Run(executor, db, "SELECT * FROM jsonb_each('{}') AS e(a, b, c)"))!;
        StringAssert.Contains("returns 2 columns", tooMany.Message);

        // A table function cannot read a column of another relation of the same FROM (that is LATERAL).
        await ExecDDL(executor, db, "CREATE TABLE docs (id int64 PRIMARY KEY, doc jsonb)");
        Assert.ThrowsAsync<CamusDBException>(async () =>
            await Run(executor, db, "SELECT e.key FROM docs, jsonb_each(docs.doc) AS e"));
    }

    private static async Task ExecDDL(CommandExecutor executor, DatabaseDescriptor db, string sql)
    {
        KvTransaction tx = await db.Transactions.BeginAsync();
        await executor.ExecuteDDLSQL(new ExecuteSQLTicket(tx, db.Name, sql, null));
        await db.Transactions.CommitAsync(tx);
    }

    private static async Task Exec(CommandExecutor executor, DatabaseDescriptor db, string sql)
    {
        KvTransaction tx = await db.Transactions.BeginAsync();
        await executor.ExecuteNonSQLQuery(new ExecuteSQLTicket(tx, db.Name, sql, null));
        await db.Transactions.CommitAsync(tx);
    }

    private async Task<(DatabaseDescriptor db, CommandExecutor executor)> SetupRows(CamusDBOptions? options = null)
    {
        (_, DatabaseDescriptor db, CommandExecutor executor) = options is null ? await CreateDatabase() : await CreateDatabase(options);
        await ExecDDL(executor, db, "CREATE TABLE t (id int64 PRIMARY KEY, g string, k string, x int64, d jsonb)");
        await Exec(executor, db,
            "INSERT INTO t (id, g, k, x, d) VALUES " +
            "(1, 'a', 'k1', 1, '{\"a\": 1}'), (2, 'a', 'k2', NULL, '[2]'), (3, 'b', 'k1', 3, NULL), " +
            "(4, 'b', 'k1', 4, '\"s\"'), (5, 'c', 'k3', 5, '1.50')");
        return (db, executor);
    }

    [Test]
    [NonParallelizable]
    public async Task Aggregates_Global_MatchPostgreSql()
    {
        (DatabaseDescriptor db, CommandExecutor executor) = await SetupRows();

        // PostgreSQL: jsonb_agg keeps NULL values as JSON null, jsonb_object_agg keeps the last value
        // of a repeated key, and both give SQL NULL over zero rows.
        Assert.AreEqual("[1, null, 3, 4, 5]", await Run(executor, db, "SELECT jsonb_agg(x) AS r FROM (SELECT id, x FROM t ORDER BY id) AS s"));
        Assert.AreEqual("[{\"a\": 1}, [2], null, \"s\", 1.50]", await Run(executor, db, "SELECT json_agg(d) AS r FROM (SELECT id, d FROM t ORDER BY id) AS s"));
        Assert.AreEqual("", await Run(executor, db, "SELECT jsonb_agg(x) AS r FROM t WHERE id > 100"));
        Assert.AreEqual("{\"k1\": 4, \"k2\": null, \"k3\": 5}", await Run(executor, db,
            "SELECT jsonb_object_agg(k, x) AS r FROM (SELECT id, k, x FROM t ORDER BY id) AS s"));

        CamusDBException nullKey = Assert.ThrowsAsync<CamusDBException>(async () =>
            await Run(executor, db, "SELECT jsonb_object_agg(CAST(NULL AS string), x) AS r FROM t"))!;
        StringAssert.Contains("field name must not be null", nullKey.Message);
    }

    [Test]
    [NonParallelizable]
    public async Task Aggregates_Grouped_AndSpilled_MatchTheInMemoryAnswer()
    {
        foreach (bool spill in new[] { false, true })
        {
            (DatabaseDescriptor db, CommandExecutor executor) = spill
                ? await SetupRows(Options with { SpillEnabled = true, ForceSpillThresholdRows = 2 })
                : await SetupRows();

            List<QueryResultRow> rows;
            KvTransaction tx = await db.Transactions.BeginAsync();
            try
            {
                (_, IAsyncEnumerable<QueryResultRow> cursor) = await executor.ExecuteSQLQuery(new ExecuteSQLTicket(tx, db.Name,
                    "SELECT g, jsonb_agg(id) AS ids, jsonb_object_agg(k, d) AS o, COUNT(*) AS c FROM t GROUP BY g", null));
                rows = await cursor.ToListAsync();
            }
            finally
            {
                await db.Transactions.RollbackIfNotCompletedAsync(tx);
            }

            Dictionary<string, QueryResultRow> byGroup = rows.ToDictionary(r => r.Row["g"].StrValue!);
            Assert.AreEqual(3, byGroup.Count, $"spill={spill}");
            CollectionAssert.AreEquivalent(new[] { "1", "2" }, Elements(byGroup["a"].Row["ids"]), $"spill={spill}");
            Assert.AreEqual("{\"k1\": {\"a\": 1}, \"k2\": [2]}", byGroup["a"].Row["o"].JsonValue, $"spill={spill}");
            Assert.AreEqual(ColumnType.Jsonb, byGroup["c"].Row["o"].Type);
            Assert.AreEqual("{\"k3\": 1.50}", byGroup["c"].Row["o"].JsonValue);
            Assert.AreEqual(2L, byGroup["b"].Row["c"].LongValue);
        }
    }

    private static IEnumerable<string> Elements(ColumnValue array) =>
        array.JsonValue!.Trim('[', ']').Split(", ");

    [Test]
    [NonParallelizable]
    public async Task CreateTableAs_TypesFunctionsAndAggregates()
    {
        (DatabaseDescriptor db, CommandExecutor executor) = await SetupRows();

        // A scalar function over an aggregate (jsonb_typeof(jsonb_agg(x))) under GROUP BY is refused by
        // CREATE TABLE AS for every function, abs(SUM(x)) included, so the two kinds are typed apart.
        await ExecDDL(executor, db,
            "CREATE TABLE c AS SELECT g, jsonb_agg(x) AS a, jsonb_object_agg(k, x) AS o FROM t GROUP BY g");
        await ExecDDL(executor, db,
            "CREATE TABLE f AS SELECT jsonb_build_object('g', g) AS b, jsonb_typeof(d) AS ty, jsonb_array_length(jsonb_build_array(x)) AS n, " +
            "d ->> 'a' AS s, jsonb_exists(d, 'a') AS e FROM t");

        KvTransaction tx = await db.Transactions.BeginAsync();
        (_, IAsyncEnumerable<QueryResultRow> cursor) = await executor.ExecuteSQLQuery(new ExecuteSQLTicket(tx, db.Name, "SHOW COLUMNS FROM c", null));
        List<QueryResultRow> columns = await cursor.ToListAsync();
        await db.Transactions.CommitAsync(tx);

        tx = await db.Transactions.BeginAsync();
        (_, cursor) = await executor.ExecuteSQLQuery(new ExecuteSQLTicket(tx, db.Name, "SHOW COLUMNS FROM f", null));
        columns.AddRange(await cursor.ToListAsync());
        await db.Transactions.CommitAsync(tx);

        string TypeOf(string name) => columns.Single(r => r.Row["Field"].StrValue == name).Row["Type"].StrValue!;
        Assert.AreEqual("JSONB", TypeOf("a"));
        Assert.AreEqual("JSONB", TypeOf("o"));
        Assert.AreEqual("JSONB", TypeOf("b"));
        Assert.AreEqual("STRING", TypeOf("ty"));
        Assert.AreEqual("INT64", TypeOf("n"));
        Assert.AreEqual("STRING", TypeOf("s"));
        Assert.AreEqual("BOOL", TypeOf("e"));
    }

    [Test]
    [NonParallelizable]
    public async Task MySqlStyleFunctions_AcceptDocuments_WithTheirOwnBehavior()
    {
        (DatabaseDescriptor db, CommandExecutor executor) = await SetupRows();

        Assert.AreEqual("1", await Run(executor, db, "SELECT json_extract(d, '$.a') AS r FROM t WHERE id = 1"));
        Assert.AreEqual("true", await Run(executor, db, "SELECT json_valid(d) AS r FROM t WHERE id = 2"));
        Assert.AreEqual("1", await Run(executor, db, "SELECT json_array_length(d) AS r FROM t WHERE id = 2"));
        Assert.AreEqual("true", await Run(executor, db, "SELECT json_contains(d, '{\"a\": 1}') AS r FROM t WHERE id = 1"));
    }
