    private static async Task<string> Evaluate(CommandExecutor executor, DatabaseDescriptor db, string expression)
    {
        KvTransaction tx = await db.Transactions.BeginAsync();
        try
        {
            (_, IAsyncEnumerable<QueryResultRow> cursor) = await executor.ExecuteSQLQuery(
                new ExecuteSQLTicket(tx, db.Name, $"SELECT coalesce(({expression})::text, '<NULL>') AS r", null));
            List<QueryResultRow> rows = await cursor.ToListAsync();
            return rows.Single().Row["r"].StrValue!;
        }
        finally
        {
            await db.Transactions.RollbackIfNotCompletedAsync(tx);
        }
    }

    [Test]
    [NonParallelizable]
    public async Task EveryOperatorCase_MatchesPostgreSql()
    {
        (_, DatabaseDescriptor db, CommandExecutor executor) = await CreateDatabase();

        StringBuilder mismatches = new();
        int failures = 0;

        foreach ((string expression, string expected) in PostgreSqlCases)
        {
            string actual;
            try
            {
                actual = await Evaluate(executor, db, expression);
            }
            catch (CamusDBException ex)
            {
                actual = "ERROR: " + ex.Message;
            }

            bool ok = expected.StartsWith("ERROR: ")
                ? actual.StartsWith("ERROR: ") && actual.Contains(expected["ERROR: ERROR:  ".Length..])
                : actual == expected;

            if (!ok)
            {
                failures++;
                mismatches.AppendLine($"{expression}\n    expected: {expected}\n    actual:   {actual}");
            }
        }

        Assert.AreEqual(0, failures, $"{failures} of {PostgreSqlCases.Length} cases differ from PostgreSQL:\n{mismatches}");
    }
