using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;

using NUnit.Framework;

using CamusDB.Core.Catalogs.Models;
using CamusDB.Core.CommandsExecutor;
using CamusDB.Core.CommandsExecutor.Models;
using CamusDB.Core.CommandsExecutor.Models.Tickets;
using CamusDB.Core.Transactions;

namespace CamusDB.Tests.CommandsExecutor;

/// <summary>
/// <c>SHOW CREATE TABLE</c> and <c>SHOW COLUMNS</c> for columns that draw from a sequence. A logical
/// dump replays <c>SHOW CREATE TABLE</c>, so a <c>DEFAULT(nextval('…'))</c> or an identity that the
/// rendering dropped left the restored table numbering nothing. The round trips here replay the
/// rendered DDL and compare the re-rendered text, which is what a dump-and-restore does.
/// </summary>
[TestFixture]
[NonParallelizable]
internal sealed class TestShowCreateTableSequenceDefaults : BaseTest
{
    private static async Task<List<QueryResultRow>> QueryAsync(CommandExecutor executor, string dbname, string sql)
    {
        DatabaseDescriptor db = await executor.OpenDatabase(dbname);
        KvTransaction tx = await db.Transactions.BeginAsync();
        (_, IAsyncEnumerable<QueryResultRow> cursor) = await executor.ExecuteSQLQuery(new ExecuteSQLTicket(tx, dbname, sql, null));
        List<QueryResultRow> rows = await cursor.ToListAsync();
        await db.Transactions.CommitAsync(tx);
        return rows;
    }

    private static async Task DdlAsync(CommandExecutor executor, string dbname, string sql)
    {
        DatabaseDescriptor db = await executor.OpenDatabase(dbname);
        KvTransaction tx = await db.Transactions.BeginAsync();
        await executor.ExecuteDDLSQL(new ExecuteSQLTicket(tx, dbname, sql, null));
    }

    private static async Task NonQueryAsync(CommandExecutor executor, string dbname, string sql)
    {
        DatabaseDescriptor db = await executor.OpenDatabase(dbname);
        KvTransaction tx = await db.Transactions.BeginAsync();
        await executor.ExecuteNonSQLQuery(new ExecuteSQLTicket(tx, dbname, sql, null));
        await db.Transactions.CommitAsync(tx);
    }

    private static async Task<string> ShowCreateTableAsync(CommandExecutor executor, string dbname, string table)
        => (await QueryAsync(executor, dbname, $"SHOW CREATE TABLE {table}"))[0].Row["Create Table"].StrValue!;

    private const string IdentityTableDdl =
        "CREATE TABLE c (id oid PRIMARY KEY, n serial, g int64 GENERATED ALWAYS AS IDENTITY, " +
        "h int64 GENERATED BY DEFAULT AS IDENTITY)";

    [Test]
    public async Task NextValDefault_IsRendered_WithTheSequenceName()
    {
        (string dbname, _, CommandExecutor executor) = await CreateDatabase();

        await DdlAsync(executor, dbname, "CREATE SEQUENCE s1");
        await DdlAsync(executor, dbname, "CREATE TABLE p (id int64 PRIMARY KEY, no int64 DEFAULT(nextval('s1')))");

        string ddl = await ShowCreateTableAsync(executor, dbname, "p");

        StringAssert.Contains("`no` INT64 NULL DEFAULT(nextval('s1'))", ddl);
    }

    /// <summary>
    /// The column stores the sequence's id, so the rendering names the sequence as it is called now —
    /// a DDL naming the old name would fail on replay.
    /// </summary>
    [Test]
    public async Task NextValDefault_FollowsASequenceRename()
    {
        (string dbname, _, CommandExecutor executor) = await CreateDatabase();

        await DdlAsync(executor, dbname, "CREATE SEQUENCE s1");
        await DdlAsync(executor, dbname, "CREATE TABLE p (id int64 PRIMARY KEY, no int64 DEFAULT(nextval('s1')))");
        await DdlAsync(executor, dbname, "ALTER SEQUENCE s1 RENAME TO order_no");

        string ddl = await ShowCreateTableAsync(executor, dbname, "p");

        StringAssert.Contains("DEFAULT(nextval('order_no'))", ddl);
        StringAssert.DoesNotContain("'s1'", ddl);
    }

    [Test]
    public async Task IdentityColumns_AreRendered_AsIdentityClauses()
    {
        (string dbname, _, CommandExecutor executor) = await CreateDatabase();

        await DdlAsync(executor, dbname, IdentityTableDdl);

        string ddl = await ShowCreateTableAsync(executor, dbname, "c");

        StringAssert.Contains("`n` INT64 NOT NULL GENERATED BY DEFAULT AS IDENTITY", ddl, "serial is a BY DEFAULT identity");
        StringAssert.Contains("`g` INT64 NOT NULL GENERATED ALWAYS AS IDENTITY", ddl);
        StringAssert.Contains("`h` INT64 NOT NULL GENERATED BY DEFAULT AS IDENTITY", ddl);
        StringAssert.DoesNotContain("nextval", ddl, "an identity names no sequence: replay creates its own");
    }

    /// <summary>
    /// Create, render, drop, replay the rendered DDL, render again: the two renderings are identical,
    /// the replayed identity columns own fresh sequences named <c>{table}_{column}_seq</c>, and the
    /// replayed table numbers its rows and refuses a value for the ALWAYS column, as the original did.
    /// </summary>
    [Test]
    public async Task RoundTrip_DropAndReplay_RecreatesDefaultsAndIdentities()
    {
        (string dbname, _, CommandExecutor executor) = await CreateDatabase();

        await DdlAsync(executor, dbname, "CREATE SEQUENCE s1");
        await DdlAsync(executor, dbname, "CREATE TABLE p (id int64 PRIMARY KEY, no int64 DEFAULT(nextval('s1')))");
        await DdlAsync(executor, dbname, IdentityTableDdl);

        string originalP = await ShowCreateTableAsync(executor, dbname, "p");
        string originalC = await ShowCreateTableAsync(executor, dbname, "c");

        // FORCE takes the owned sequences with the table, so the replay starts from what an empty
        // database holds for c: no sequences of its own.
        await DdlAsync(executor, dbname, "DROP TABLE p FORCE");
        await DdlAsync(executor, dbname, "DROP TABLE c FORCE");

        Assert.IsFalse((await executor.OpenDatabase(dbname)).Schema.Sequences.ContainsKey("c_n_seq"));

        await DdlAsync(executor, dbname, originalP);
        await DdlAsync(executor, dbname, originalC);

        Assert.AreEqual(originalP, await ShowCreateTableAsync(executor, dbname, "p"));
        Assert.AreEqual(originalC, await ShowCreateTableAsync(executor, dbname, "c"));

        Schema schema = (await executor.OpenDatabase(dbname)).Schema;
        string tableId = schema.Tables["c"].Id!;
        foreach (string owned in new[] { "c_n_seq", "c_g_seq", "c_h_seq" })
        {
            Assert.IsTrue(schema.Sequences.TryGetValue(owned, out SequenceSchema? sequence), owned + " was not created");
            Assert.AreEqual(tableId, sequence!.OwnedByTableId, owned + " must be owned by the replayed table");
        }

        await NonQueryAsync(executor, dbname, "INSERT INTO p (id) VALUES (1)");
        await NonQueryAsync(executor, dbname, "INSERT INTO c (id) VALUES (gen_id())");

        List<QueryResultRow> pRows = await QueryAsync(executor, dbname, "SELECT no FROM p");
        Assert.AreEqual(1L, pRows[0].Row["no"].LongValue);

        List<QueryResultRow> cRows = await QueryAsync(executor, dbname, "SELECT n, g, h FROM c");
        Assert.AreEqual(1L, cRows[0].Row["n"].LongValue);
        Assert.AreEqual(1L, cRows[0].Row["g"].LongValue);
        Assert.AreEqual(1L, cRows[0].Row["h"].LongValue);

        CamusDB.Core.CamusDBException refused = Assert.ThrowsAsync<CamusDB.Core.CamusDBException>(
            () => NonQueryAsync(executor, dbname, "INSERT INTO c (id, g) VALUES (gen_id(), 5)"))!;
        StringAssert.Contains("GENERATED ALWAYS AS IDENTITY", refused.Message);
    }

    /// <summary>
    /// The dump case proper: the rendered DDL replayed into a different, empty database (after the
    /// free-standing sequence it names) re-creates the same table.
    /// </summary>
    [Test]
    public async Task RoundTrip_ReplayIntoAnEmptyDatabase()
    {
        (string source, _, CommandExecutor executor) = await CreateDatabase();

        await DdlAsync(executor, source, "CREATE SEQUENCE s1");
        await DdlAsync(executor, source,
            "CREATE TABLE p (id int64 PRIMARY KEY, no int64 NOT NULL DEFAULT(nextval('s1')), " +
            "n serial, g int64 GENERATED ALWAYS AS IDENTITY)");

        string original = await ShowCreateTableAsync(executor, source, "p");

        (string target, _, CommandExecutor targetExecutor) = await CreateDatabase();

        await DdlAsync(targetExecutor, target, "CREATE SEQUENCE s1");
        await DdlAsync(targetExecutor, target, original);

        Assert.AreEqual(original, await ShowCreateTableAsync(targetExecutor, target, "p"));
        Assert.IsTrue((await targetExecutor.OpenDatabase(target)).Schema.Sequences.ContainsKey("p_n_seq"));
        Assert.IsTrue((await targetExecutor.OpenDatabase(target)).Schema.Sequences.ContainsKey("p_g_seq"));
    }

    /// <summary>
    /// <c>SHOW COLUMNS</c> keeps its six-field shape: a <c>nextval</c> default appears in
    /// <c>Default</c>, and an identity in <c>Extra</c>, the way MySQL reports an auto-increment column.
    /// </summary>
    [Test]
    public async Task ShowColumns_ReportsNextValDefaultAndIdentity()
    {
        (string dbname, _, CommandExecutor executor) = await CreateDatabase();

        await DdlAsync(executor, dbname, "CREATE SEQUENCE s1");
        await DdlAsync(executor, dbname,
            "CREATE TABLE c (id oid PRIMARY KEY, no int64 DEFAULT(nextval('s1')), n serial, " +
            "g int64 GENERATED ALWAYS AS IDENTITY, h int64 GENERATED BY DEFAULT AS IDENTITY, k int64 DEFAULT(3))");

        Dictionary<string, Dictionary<string, string?>> byField = (await QueryAsync(executor, dbname, "SHOW COLUMNS FROM c"))
            .ToDictionary(
                r => r.Row["Field"].StrValue!,
                r => r.Row.ToDictionary(kv => kv.Key, kv => kv.Value.StrValue));

        Assert.That(byField["no"].Keys, Is.EquivalentTo(new[] { "Field", "Type", "Null", "Key", "Default", "Extra" }));

        Assert.AreEqual("nextval('s1')", byField["no"]["Default"]);
        Assert.AreEqual("", byField["no"]["Extra"]);

        Assert.AreEqual("GENERATED BY DEFAULT AS IDENTITY", byField["n"]["Extra"]);
        Assert.AreEqual("GENERATED ALWAYS AS IDENTITY", byField["g"]["Extra"]);
        Assert.AreEqual("GENERATED BY DEFAULT AS IDENTITY", byField["h"]["Extra"]);
        Assert.AreEqual("NULL", byField["g"]["Default"]);

        Assert.AreEqual("3", byField["k"]["Default"]);
        Assert.AreEqual("", byField["k"]["Extra"]);
    }
}
