using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using NUnit.Framework;
using CamusDB.Core.Catalogs.Models;
using CamusDB.Core.CommandsExecutor.Models;
using CamusDB.Core.CommandsExecutor.Models.Tickets;
using CamusDB.Core.Transactions;
using CamusDB.Core.Util.ObjectIds;

namespace CamusDB.Tests.Cluster;

/// <summary>
/// The schedule seen in the field: a staged schema change is driven by the schema leader, which loses
/// the leadership in the middle of its fill, and the next leader's resume finishes the job while the
/// former driver is still running. The former driver used to keep working beside its successor until
/// a step was refused, and then answered its client "nothing was committed, retry", after which the
/// retry found the column already there. Now its fill is cancelled when the leadership is lost, its
/// record writes are refused by the successor's newer term, and its statement is answered from what
/// the successor did: it succeeds, with the element published exactly once.
/// </summary>
[TestFixture]
// Serial: boots a multi-node in-process cluster. Concurrent clusters contend for ports and skew
// each other's Raft election timing.
[NonParallelizable]
public sealed class TestClusterSchemaChangeHandover
{
    /// <summary>Several fill batches of 256 and several index batches of 500, so a seam fires inside the long phase.</summary>
    private const int Rows = 1_200;
    private static readonly TimeSpan Soon = TimeSpan.FromSeconds(60);

    [Test]
    public async Task AddColumn_LeadershipMovesDuringTheFill_StatementSucceedsAndTheColumnIsFilledOnce()
    {
        await using InProcessSchemaCluster cluster = await InProcessSchemaCluster.StartAsync(nodeCount: 3, wireLeaderForwarder: true);
        string db = cluster.NextSchemaLogDatabaseName();
        await cluster.OpenDatabaseOnAllNodesAsync(db);
        await SeedAsync(cluster, db);

        InProcessSchemaCluster.Node leader = await cluster.WaitForSchemaLeaderNodeAsync(db);
        InProcessSchemaCluster.Node[] followers = cluster.Nodes.Where(n => n.Index != leader.Index).ToArray();
        InProcessSchemaCluster.Node sender = followers[0];
        InProcessSchemaCluster.Node successor = followers[1];

        long term = leader.Kahuna.SchemaLeaderTerm(db);
        Assert.That(term, Is.GreaterThan(0), "the leader reads a term it can fence with");

        TaskCompletionSource reached = new(TaskCreationOptions.RunContinuationsAsynchronously);
        TaskCompletionSource released = new(TaskCreationOptions.RunContinuationsAsynchronously);
        int fires = 0;
        leader.Executor.TestInterceptBeforeFillBatchLock = async () =>
        {
            if (Interlocked.Increment(ref fires) != 1)
                return;
            reached.TrySetResult();
            await released.Task;
        };

        // Sent to a follower and forwarded to the leader, as in the field.
        Task addColumn = DdlAsync(sender, db, "ALTER TABLE accounts ADD COLUMN seq INT64 GENERATED BY DEFAULT AS IDENTITY");

        try
        {
            Assert.That(await CompletesWithin(reached.Task, Soon), Is.True, "the leader's fill reaches its first batch");
            Assert.That(leader.Database!.DdlGate.IsTableHeld("accounts"), Is.True, "the fill holds its table on the leader");

            // The leadership moves while the driver is inside its fill. The successor's resume finds
            // the job at WriteOnly, stamps its newer term on the record, fills the table and publishes.
            await cluster.TransferSchemaLeadershipAsync(db, successor, timeout: TimeSpan.FromSeconds(15));
            Assert.That(successor.Kahuna.SchemaLeaderTerm(db), Is.GreaterThan(term), "the successor leads in a newer term");

            Assert.That(await WaitUntilAsync(() => ColumnState(successor, "seq") == SchemaElementState.Public, Soon), Is.True,
                "the successor publishes the column while the former driver is still paused in its fill");

            // The record goes once the Public step is acknowledged, a moment after the state shows it.
            Assert.That(await WaitUntilAsync(() => RecordAsync(successor).GetAwaiter().GetResult() is null, Soon), Is.True,
                "the successor deleted the record when it reached Public");
        }
        finally
        {
            released.TrySetResult();
            leader.Executor.TestInterceptBeforeFillBatchLock = null;
        }

        // The former driver wakes, finds its leadership gone and its job finished by the successor,
        // and answers its statement from that outcome.
        Assert.That(await CompletesWithin(addColumn, Soon), Is.True, "the statement is answered");
        await addColumn;

        await cluster.WaitForSchemaConvergenceAsync(db, successor.Database!.Schema.SchemaVersion, timeout: TimeSpan.FromSeconds(60));

        foreach (InProcessSchemaCluster.Node node in cluster.Nodes)
        {
            Assert.That(ColumnState(node, "seq"), Is.EqualTo(SchemaElementState.Public), $"node {node.Index}: column Public");
            Assert.That(node.Database!.DdlGate.HeldTableCount, Is.EqualTo(0), $"node {node.Index}: nothing holds a table");
            Assert.That(node.Database.SchemaDdlSemaphore.CurrentCount, Is.EqualTo(1), $"node {node.Index}: the gate is free");
            Assert.That(await node.Executor.Catalogs.LoadCoordinatorJobsAsync(node.Database), Is.Empty, $"node {node.Index}: no job left");

            List<QueryResultRow> rows = await RowsAsync(node, db, "SELECT id, seq FROM accounts");
            Assert.That(rows, Has.Count.EqualTo(Rows), $"node {node.Index}: every row");
            Assert.That(rows.Select(r => r.Row["seq"].Type), Is.All.EqualTo(ColumnType.Integer64), $"node {node.Index}: every row holds a value");
            Assert.That(rows.Select(r => r.Row["seq"].LongValue).Distinct().Count(), Is.EqualTo(Rows), $"node {node.Index}: one identity value per row");
        }

        Assert.That(fires, Is.EqualTo(1), "the former driver ran no batch after it woke");
    }

    [Test]
    public async Task CreateIndex_LeadershipMovesDuringTheBackfill_StatementSucceedsAndTheIndexIsComplete()
    {
        await using InProcessSchemaCluster cluster = await InProcessSchemaCluster.StartAsync(nodeCount: 3, wireLeaderForwarder: true);
        string db = cluster.NextSchemaLogDatabaseName();
        await cluster.OpenDatabaseOnAllNodesAsync(db);
        await SeedAsync(cluster, db);

        InProcessSchemaCluster.Node leader = await cluster.WaitForSchemaLeaderNodeAsync(db);
        InProcessSchemaCluster.Node[] followers = cluster.Nodes.Where(n => n.Index != leader.Index).ToArray();
        InProcessSchemaCluster.Node sender = followers[0];
        InProcessSchemaCluster.Node successor = followers[1];

        TaskCompletionSource reached = new(TaskCreationOptions.RunContinuationsAsynchronously);
        TaskCompletionSource released = new(TaskCreationOptions.RunContinuationsAsynchronously);
        int fires = 0;
        leader.Executor.TestInterceptAfterBackfillCheckpoint = async () =>
        {
            if (Interlocked.Increment(ref fires) != 1)
                return;
            reached.TrySetResult();
            await released.Task;
        };

        Task createIndex = DdlAsync(sender, db, "CREATE INDEX acct_balance ON accounts (balance)");

        try
        {
            Assert.That(await CompletesWithin(reached.Task, Soon), Is.True, "the leader's backfill reaches its first checkpoint");

            await cluster.TransferSchemaLeadershipAsync(db, successor, timeout: TimeSpan.FromSeconds(15));

            Assert.That(await WaitUntilAsync(() => IndexState(successor, "acct_balance") == SchemaElementState.Public, Soon), Is.True,
                "the successor publishes the index while the former driver is still paused in its backfill");
        }
        finally
        {
            released.TrySetResult();
            leader.Executor.TestInterceptAfterBackfillCheckpoint = null;
        }

        Assert.That(await CompletesWithin(createIndex, Soon), Is.True, "the statement is answered");
        await createIndex;

        await cluster.WaitForSchemaConvergenceAsync(db, successor.Database!.Schema.SchemaVersion, timeout: TimeSpan.FromSeconds(60));

        foreach (InProcessSchemaCluster.Node node in cluster.Nodes)
        {
            Assert.That(IndexState(node, "acct_balance"), Is.EqualTo(SchemaElementState.Public), $"node {node.Index}: index Public");
            Assert.That(node.Database!.DdlGate.HeldTableCount, Is.EqualTo(0), $"node {node.Index}: nothing holds a table");
            Assert.That(node.Database.SchemaDdlSemaphore.CurrentCount, Is.EqualTo(1), $"node {node.Index}: the gate is free");
            Assert.That(await node.Executor.Catalogs.LoadCoordinatorJobsAsync(node.Database), Is.Empty, $"node {node.Index}: no job left");

            List<(long balance, ObjectIdValue rowId)> entries = await IndexEntriesAsync(node, db);
            Assert.That(entries, Has.Count.EqualTo(Rows), $"node {node.Index}: one entry per row");
            Assert.That(entries.Select(e => e.rowId).Distinct().Count(), Is.EqualTo(Rows), $"node {node.Index}: no row indexed twice");
        }
    }

    // -----------------------------------------------------------------------
    // Helpers
    // -----------------------------------------------------------------------

    private static async Task<bool> CompletesWithin(Task task, TimeSpan within)
        => ReferenceEquals(await Task.WhenAny(task, Task.Delay(within)), task);

    private static async Task<bool> WaitUntilAsync(Func<bool> condition, TimeSpan within)
    {
        DateTime deadline = DateTime.UtcNow.Add(within);
        while (DateTime.UtcNow < deadline)
        {
            if (condition())
                return true;
            await Task.Delay(50);
        }
        return condition();
    }

    private static SchemaElementState ColumnState(InProcessSchemaCluster.Node node, string column) =>
        node.Database?.Schema.Tables["accounts"].Columns?.FirstOrDefault(c => c.Name == column)?.State ?? SchemaElementState.Absent;

    private static SchemaElementState IndexState(InProcessSchemaCluster.Node node, string index) =>
        node.Database?.Schema.Tables["accounts"].Indexes?.FirstOrDefault(ix => ix.Name == index)?.State ?? SchemaElementState.Absent;

    private static string TableId(InProcessSchemaCluster.Node node) => node.Database!.Schema.Tables["accounts"].Id!;

    private static Task<PersistedCoordinatorJob?> RecordAsync(InProcessSchemaCluster.Node node) =>
        node.Executor.Catalogs.TryLoadCoordinatorJobAsync(node.Database!, TableId(node), "seq");

    private static async Task SeedAsync(InProcessSchemaCluster cluster, string db)
    {
        long version = 0;
        await cluster.RunOnSchemaLeaderAsync(db, async leader =>
        {
            await DdlAsync(leader, db, "CREATE TABLE accounts (id INT64 PRIMARY KEY NOT NULL, balance INT64 NOT NULL, version INT64 NOT NULL)");

            const int rowsPerStatement = 200;
            for (int start = 1; start <= Rows; start += rowsPerStatement)
            {
                int end = Math.Min(Rows, start + rowsPerStatement - 1);
                string values = string.Join(", ", Enumerable.Range(start, end - start + 1).Select(i => $"({i}, {1_000_000 + i}, 0)"));
                await DmlAsync(leader, db, "INSERT INTO accounts (id, balance, version) VALUES " + values);
            }

            version = leader.Database!.Schema.SchemaVersion;
        });

        await cluster.WaitForSchemaConvergenceAsync(db, version, timeout: TimeSpan.FromSeconds(30));
    }

    private static Task DdlAsync(InProcessSchemaCluster.Node node, string db, string sql) =>
        node.Executor.ExecuteDDLSQL(new ExecuteSQLTicket(txnState: null!, database: db, sql: sql, parameters: null));

    private static async Task DmlAsync(InProcessSchemaCluster.Node node, string db, string sql)
    {
        KvTransaction tx = await node.Database!.Transactions.BeginAsync();
        try
        {
            await node.Executor.ExecuteNonSQLQuery(new ExecuteSQLTicket(tx, db, sql, null));
            await node.Database.Transactions.CommitAsync(tx);
        }
        finally
        {
            await node.Database.Transactions.RollbackIfNotCompletedAsync(tx);
        }
    }

    private static async Task<List<QueryResultRow>> RowsAsync(InProcessSchemaCluster.Node node, string db, string sql)
    {
        KvTransaction tx = await node.Database!.Transactions.BeginAsync();
        try
        {
            (_, IAsyncEnumerable<QueryResultRow> cursor) = await node.Executor.ExecuteSQLQuery(new ExecuteSQLTicket(tx, db, sql, null));

            List<QueryResultRow> rows = [];
            await foreach (QueryResultRow row in cursor)
                rows.Add(row);
            return rows;
        }
        finally
        {
            await node.Database.Transactions.RollbackIfNotCompletedAsync(tx);
        }
    }

    /// <summary>Every entry of the new index as this node's store holds it.</summary>
    private static async Task<List<(long balance, ObjectIdValue rowId)>> IndexEntriesAsync(InProcessSchemaCluster.Node node, string db)
    {
        TableIndexSchema index = node.Database!.Schema.Tables["accounts"].Indexes!.First(ix => ix.Name == "acct_balance");
        TableDescriptor table = await node.Executor.OpenTable(new OpenTableTicket(db, "accounts"));

        KvTransaction tx = await node.Database.Transactions.BeginAsync();
        try
        {
            List<(long, ObjectIdValue)> entries = [];
            await foreach ((CompositeColumnValue key, ObjectIdValue rowId, _) in table.Store.ScanIndex(tx, index.KvId, [ColumnType.Integer64], from: null, to: null, unique: false))
                entries.Add((key.Values[0].LongValue, rowId));
            return entries;
        }
        finally
        {
            await node.Database.Transactions.RollbackIfNotCompletedAsync(tx);
        }
    }
}
