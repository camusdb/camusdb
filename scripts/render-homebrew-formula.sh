#!/usr/bin/env bash
#
# Write the Homebrew formula for one release to stdout. The release workflow attaches the result to
# the GitHub release and commits it to the tap (camusdb/homebrew-tap) as Formula/camusdb.rb, so users
# install with:
#
#   brew install camusdb/tap/camusdb
#
# The formula downloads the prebuilt self-contained archives that scripts/package-release.sh builds;
# Homebrew compiles nothing. It reads each archive's checksum from the .sha256 file beside it, so all
# four platform archives must be in <archive-dir>.
#
# Usage:
#   scripts/render-homebrew-formula.sh <version> <archive-dir> [base-url] > camusdb.rb
#
# base-url defaults to the GitHub release download URL for tag v<version>. A local test passes a
# file:// URL instead.
#
# The installed service keeps its configuration and data under $(brew --prefix)/var/camusdb, through
# CAMUS_HOME, because a launchd/systemd service must not depend on the files in one user's home
# directory. A node started by hand from a shell still reads ~/.camusdb/config.yml as usual.

set -euo pipefail

VERSION="${1:?usage: scripts/render-homebrew-formula.sh <version> <archive-dir> [base-url]}"
ARCHIVE_DIR="${2:?usage: scripts/render-homebrew-formula.sh <version> <archive-dir> [base-url]}"
BASE_URL="${3:-https://github.com/camusdb/camusdb/releases/download/v$VERSION}"

sha_of() {
  local file="$ARCHIVE_DIR/camusdb-$VERSION-$1.tar.gz.sha256"
  if [[ ! -f "$file" ]]; then
    echo "error: $file is missing" >&2
    exit 1
  fi
  awk '{ print $1 }' "$file"
}

SHA_OSX_ARM64="$(sha_of osx-arm64)"
SHA_OSX_X64="$(sha_of osx-x64)"
SHA_LINUX_ARM64="$(sha_of linux-arm64)"
SHA_LINUX_X64="$(sha_of linux-x64)"

cat <<RUBY
# This file is generated by scripts/render-homebrew-formula.sh in camusdb/camusdb.
# Do not edit it in the tap: the next release overwrites it.
class Camusdb < Formula
  desc "Distributed SQL database"
  homepage "https://github.com/camusdb/camusdb"
  # Explicit, because Homebrew can read the "64" in "...-osx-arm64.tar.gz" as the version.
  version "$VERSION"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "$BASE_URL/camusdb-$VERSION-osx-arm64.tar.gz"
      sha256 "$SHA_OSX_ARM64"
    end
    on_intel do
      url "$BASE_URL/camusdb-$VERSION-osx-x64.tar.gz"
      sha256 "$SHA_OSX_X64"
    end
  end

  on_linux do
    on_arm do
      url "$BASE_URL/camusdb-$VERSION-linux-arm64.tar.gz"
      sha256 "$SHA_LINUX_ARM64"
    end
    on_intel do
      url "$BASE_URL/camusdb-$VERSION-linux-x64.tar.gz"
      sha256 "$SHA_LINUX_X64"
    end
  end

  def install
    libexec.install Dir["*"]
    # The .NET host resolves the symlink to find the runtime and the assemblies beside it.
    bin.install_symlink libexec/"CamusDB" => "camusdb"
  end

  # Write the starter configuration for the service once. A later upgrade keeps the operator's edits.
  post_install_steps do
    unless_path_exists "camusdb/config.yml", base: :var do
      run "camusdb", base: :bin, args: ["init"], env: { "CAMUS_HOME" => "{{var}}/camusdb" },
          writable_paths: ["camusdb"], writable_base: :var
    end
  end

  def caveats
    <<~EOS
      The service reads #{var}/camusdb/config.yml and stores its data in #{var}/camusdb/data.
      It serves the JSON/REST API on port 5095 and gRPC on port 5096.

      A node started by hand with \`camusdb\` reads ~/.camusdb/config.yml instead.
      Write that file with \`camusdb init\`.
    EOS
  end

  service do
    run [opt_bin/"camusdb"]
    environment_variables CAMUS_HOME: var/"camusdb"
    working_dir var/"camusdb"
    keep_alive true
    log_path var/"log/camusdb.log"
    error_log_path var/"log/camusdb.log"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/camusdb --version")

    ENV["CAMUS_HOME"] = (testpath/"home").to_s
    system bin/"camusdb", "init"
    assert_path_exists testpath/"home/config.yml"
  end
end
RUBY
