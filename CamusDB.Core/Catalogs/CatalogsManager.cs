/// <summary>
/// Maintains references to all objects in the database.
/// Allows knowing the description and characteristics of tables, views, indexes, etc.
/// </summary>
public sealed class CatalogsManager
{
    private readonly ILogger<ICamusDB> logger;

    private readonly SchemaCheckpointWriter checkpoints;

    private readonly SchemaChangePublisher publisher;

    /// <summary>
    /// Test hook, written through to <see cref="SchemaCheckpointWriter"/>: when non-null, every
    /// checkpoint persist throws it instead of writing, so a test can drive the exhausted-retry path
    /// without a real KV fault. Kept on the facade because that is where the tests reach it.
    /// </summary>
    internal Exception? TestPersistCheckpointException {
        get => checkpoints.TestPersistCheckpointException;
        set => checkpoints.TestPersistCheckpointException = value;
    }

    public CatalogsManager(ILogger<ICamusDB> logger)
    {
        this.logger = logger;

        checkpoints = new(logger);
        publisher = new(checkpoints, logger);
    }

    /// <summary>
    /// Adds a new table object to the database schema as well as its indexes.
    /// <paramref name="tableId"/> is the pre-allocated, globally-unique id for the new table,
    /// produced by the proposer via <see cref="DatabaseRegistry.AllocateTableIdAsync"/> before
    /// this method is called. It is carried verbatim in the replicated payload so every node
    /// applies the same id; the caller is responsible for ensuring it was not generated by
    /// a follower.
    /// </summary>
    /// <exception cref="CamusDBException"></exception>
    public Task<TableSchema> CreateTable(DatabaseDescriptor database, CreateTableTicket ticket, KvTransaction tx, string tableId)
        => CreateTableReplicatedAsync(database, ticket, tx, tableId);

    /// <summary>
    /// Modifies an existing table object allowing to add or remove columns.
    /// </summary>
    /// <param name="database"></param>
    /// <param name="ticket"></param>
    /// <returns></returns>
    /// <exception cref="CamusDBException"></exception>
    public Task<TableSchema> AlterTable(DatabaseDescriptor database, AlterColumnTicket ticket, KvTransaction tx)
        => AlterTableReplicatedAsync(database, ticket, tx);

    /// <summary>
    /// Removes a table from the live schema via a replicated <see cref="SchemaOp.DropTable"/> delta.
    /// When <paramref name="deferred"/> is <c>true</c> the drop is recoverable: the schema checkpoint
    /// that deletes the per-table meta key also writes the table's orphan record in the same
    /// transaction (see <see cref="PersistDroppedTableAsync"/>), so a crash can never detach the table
    /// without leaving a recovery record. The caller must have already retained the row/index data.
    /// </summary>
    public Task<TableSchema?> DropTableSchema(DatabaseDescriptor database, string tableName, string tableId, KvTransaction tx, bool deferred = false)
        => DropTableReplicatedAsync(database, tableName, tx, deferred);

    /// <summary>
    /// Allows querying the current schema of a table object.
    /// </summary>
    /// <param name="database"></param>
    /// <param name="tableName"></param>
    /// <returns></returns>
    /// <exception cref="CamusDBException"></exception>
    public TableSchema GetTableSchema(DatabaseDescriptor database, string tableName) // @todo return a snapshot instead of the schema
    {
        if (database.Schema.Tables.TryGetValue(tableName, out TableSchema? tableSchema))
            return tableSchema;

        throw new CamusDBException(CamusDBErrorCodes.TableDoesntExist, $"Table '{tableName}' doesn't exist");
    }

    /// <summary>
    /// Returns true if a table exists
    /// </summary>
    /// <param name="database"></param>
    /// <param name="tableName"></param>
    /// <returns></returns>
    public bool TableExists(DatabaseDescriptor database, string tableName)
    {
        return database.Schema.Tables.ContainsKey(tableName);
    }

    private async Task<TableSchema> CreateTableReplicatedAsync(DatabaseDescriptor database, CreateTableTicket ticket, KvTransaction tx, string tableId)
    {
        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            entry = SchemaChangeEntryFactory.CreateTableEntry(database, ticket, tx, tableId);
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);
        return GetTableSchema(database, ticket.TableName);
    }

    private async Task<TableSchema> AlterTableReplicatedAsync(DatabaseDescriptor database, AlterColumnTicket ticket, KvTransaction tx)
    {
        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            entry = SchemaChangeEntryFactory.AlterTableEntry(database, ticket, tx);
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);
        return GetTableSchema(database, ticket.TableName);
    }

    private async Task<TableSchema?> DropTableReplicatedAsync(DatabaseDescriptor database, string tableName, KvTransaction tx, bool deferred)
    {
        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            entry = SchemaChangeEntryFactory.DropTableEntry(database, tableName, tx, deferred);
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);
        return null;
    }

    /// <summary>
    /// Reattaches an orphaned (deferred-dropped) table to the live schema under <paramref name="newName"/>,
    /// reusing its preserved id so it reads its retained rows and index entries. Modeled as a dedicated
    /// <see cref="SchemaOp.RelinkTable"/> delta rebuilt from the orphan's captured schema — preserving the
    /// original table id, column ids, index definitions, check constraints, <b>and schema version</b> — so
    /// every node reconstructs an identical table and rows written under the drop-time version decode
    /// correctly. The apply configures a lazy schema-history loader against the retained
    /// <c>{dbId}/meta/history:{tableId}:*</c> keys, so rows written under earlier pre-<c>ALTER</c> versions
    /// also decode (immediately and after reopen). The orphan record is removed in the caller's DDL
    /// transaction after the reattach is applied.
    ///
    /// <para><b>Ordering:</b> reattach-then-delete-orphan, mirroring database relink. A crash after the
    /// reattach but before the orphan-record delete commits leaves a live table with a stale orphan
    /// record; the garbage collector skips orphan records whose table exists in the live schema.</para>
    /// </summary>
    public async Task<TableSchema> RelinkTable(DatabaseDescriptor database, OrphanTableRecord orphan, string newName, KvTransaction tx)
    {
        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            entry = SchemaChangeEntryFactory.RelinkTableEntry(database, orphan, newName, tx);
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);

        TableSchema reattached = GetTableSchema(database, newName);

        // Restore the system-schema table object and persist it in the DDL transaction, mirroring
        // TableCreator (deferred drop removed it). Without this the live schema has the table but the
        // system schema does not, an asymmetry with the create/drop paths.
        RegisterTableSystemObject(database, reattached);
        await PersistSystemMetaAsync(database, tx).ConfigureAwait(false);

        // The table is live again — drop the orphan record so the GC leaves the reattached data alone.
        await DeleteTableOrphanAsync(database, orphan.TableId, tx).ConfigureAwait(false);

        return reattached;
    }

    /// <summary>
    /// Publishes a retired contents generation as a <b>new</b> relation, so the rows a
    /// <c>TRUNCATE</c> made unreachable can be read again.
    /// </summary>
    /// <remarks>
    /// <para><b>A fresh logical id is mandatory.</b> The retired key-space is named by a storage id,
    /// and on a relation's first truncate that storage id <em>is</em> the still-live source relation's
    /// id. Reusing it would publish a second relation under an id that is already live — two names for
    /// one identity, with the grants and dependencies of the source silently attached to the recovery.
    /// The recovered relation therefore gets a new id and points at the retired key-space through
    /// <see cref="TableSchema.StorageId"/>, which is exactly the separation that made the truncate
    /// cheap in the first place.</para>
    ///
    /// <para>The captured column layouts are copied under the new id because the retained rows carry
    /// the source relation's schema versions, and the append-only history keys that describe those
    /// versions live under the source's id — where the recovered relation cannot reach them.</para>
    ///
    /// <para>Order is reattach, then delete the record. A crash in between leaves a live relation with
    /// a stale record; the collector recognises that from <see cref="OrphanTableRecord.RelinkTargetId"/>
    /// and removes the record without touching the storage the recovery now owns.</para>
    /// </remarks>
    public async Task<TableSchema> RelinkRetiredContents(
        DatabaseDescriptor database, OrphanTableRecord orphan, string newTableId, string newName, KvTransaction tx)
    {
        TableSchema captured = orphan.Schema;

        OrphanTableRecord published = new()
        {
            Kind = orphan.Kind,
            TableId = newTableId,
            FormerName = orphan.FormerName,
            DroppedAt = orphan.DroppedAt,
            SourceTableId = orphan.SourceTableId,
            RetiredStorageId = orphan.RetiredStorageId,
            RelinkTargetId = newTableId,
            Schema = new()
            {
                Id = newTableId,
                // The recovered relation reads the retired key-space; its own id names nothing on disk.
                StorageId = orphan.RetiredStorageId,
                Version = captured.Version,
                Name = newName,
                Columns = captured.Columns,
                Indexes = captured.Indexes,
                CheckConstraints = captured.CheckConstraints,
                Settings = captured.Settings,
                Comment = captured.Comment,
                Kind = captured.Kind,
                ViewDefinition = captured.ViewDefinition,
                IsPopulated = captured.IsPopulated,
                RefreshedAt = captured.RefreshedAt,
            }
        };

        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            entry = SchemaChangeEntryFactory.RelinkTableEntry(database, published, newName, tx);
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);

        TableSchema reattached = GetTableSchema(database, newName);

        RegisterTableSystemObject(database, reattached);
        await PersistSystemMetaAsync(database, tx).ConfigureAwait(false);

        // Copy the captured layouts under the new id so a row written under an older version of the
        // source relation still decodes through the recovered one.
        IKahuna kahuna = database.Kahuna.Kahuna;
        foreach (TableSchemaHistory history in captured.SchemaHistory ?? [])
        {
            byte[] historyBytes = MetaJsonSerializer.Serialize(history, MetaJsonContext.Default.TableSchemaHistory);
            await MetaKeyWriter.WriteMetaKey(kahuna, tx, MetaKeys.HistoryKey(database.Id, newTableId, history.Version), historyBytes).ConfigureAwait(false);
        }

        // Addressed by the key-space it protected, not by the relation that now owns it.
        await DeleteTableOrphanAsync(database, orphan.RetiredStorageId, tx).ConfigureAwait(false);

        return reattached;
    }

    /// <summary>
    /// Stamps a retired-contents record with the relation a recovery is about to publish, in its own
    /// committed transaction.
    /// </summary>
    /// <remarks>
    /// Written <b>before</b> the relation is published, so a crash between the two leaves evidence.
    /// Without it the collector cannot tell a recovery that half-finished from one that never started,
    /// and would purge the storage the half-finished recovery is about to hand back.
    /// </remarks>
    public async Task RecordRelinkTargetAsync(DatabaseDescriptor database, OrphanTableRecord orphan, string targetId)
    {
        orphan.RelinkTargetId = targetId;

        byte[] bytes = MetaJsonSerializer.Serialize(orphan, MetaJsonContext.Default.OrphanTableRecord);

        KvTransaction tx = await database.Transactions.BeginAsync(
            CamusIsolationLevel.ReadCommitted, CamusTransactionMode.ReadWrite
        ).ConfigureAwait(false);
        try
        {
            await MetaKeyWriter.WriteMetaKey(database.Kahuna.Kahuna, tx, MetaKeys.OrphanKey(database.Id, orphan.RetiredStorageId), bytes).ConfigureAwait(false);
            await database.Transactions.CommitAsync(tx).ConfigureAwait(false);
        }
        finally
        {
            await database.Transactions.RollbackIfNotCompletedAsync(tx).ConfigureAwait(false);
        }
    }

    /// <summary>
    /// Adds (or re-adds) the system-schema table object for <paramref name="tableSchema"/>, keyed by its
    /// immutable id. Shared by table creation and relink so both keep <c>SystemSchema.Tables</c> in sync
    /// with the live schema. In-memory only; the caller persists via <see cref="PersistSystemMetaAsync"/>.
    /// </summary>
    public void RegisterTableSystemObject(DatabaseDescriptor database, TableSchema tableSchema)
    {
        database.SystemSchemaSemaphore.Wait();
        try
        {
            database.SystemSchema.Tables.TryAdd(
                tableSchema.Id ?? "",
                new DatabaseTableObject(
                    type: DatabaseObjectType.Table,
                    id: tableSchema.Id ?? "",
                    name: tableSchema.Name!,
                    startOffset: ""));
        }
        finally
        {
            database.SystemSchemaSemaphore.Release();
        }
    }

