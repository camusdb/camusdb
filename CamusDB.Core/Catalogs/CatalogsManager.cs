    /// <summary>
    /// Proposes a <see cref="SchemaOp.SetTableSettings"/> delta and replicates it to all cluster nodes,
    /// so every node's in-memory <see cref="TableSchema.Settings"/> updates and the KV checkpoint is
    /// rewritten. Advances the database schema version (like check constraints) but not
    /// <see cref="TableSchema.Version"/> — settings do not affect row encoding.
    ///
    /// <para><b>Both modes use this path.</b> A standalone node is the only member of its own schema
    /// group, so proposing costs it a single-node commit and buys the same guarantees the cluster gets:
    /// the database schema version and the descriptor's head-version fence advance together, from the
    /// one place that advances them for every other schema operation. The earlier standalone shortcut
    /// wrote the table blob directly and left the version untouched, which made a background sweep that
    /// keys on the database schema version unable to notice a table's settings changing at all — TTL
    /// could be switched on and the sweep would never see it. Changing settings <em>is</em> a schema
    /// change; do not reintroduce a mode-specific path that pretends otherwise.</para>
    /// </summary>
    public async Task ReplicateSetTableSettingsAsync(
        DatabaseDescriptor database,
        string tableName,
        IReadOnlyDictionary<string, string> settings,
        IReadOnlyCollection<string>? removedKeys = null)
    {
        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            entry = new()
            {
                Database = database.Id,
                FromVersion = database.Schema.SchemaVersion,
                ToVersion = database.Schema.SchemaVersion + 1,
                Op = SchemaOp.SetTableSettings,
                Payload = Serializator.Serialize(new SchemaSetTableSettingsPayload
                {
                    TableName = tableName,
                    Settings = new Dictionary<string, string>(settings, StringComparer.Ordinal),
                    RemovedKeys = removedKeys is null ? [] : [.. removedKeys]
                })
            };
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);
    }

    /// <summary>
    /// Proposes a <see cref="SchemaOp.SetComment"/> delta and replicates it, so every node's
    /// in-memory schema carries the new comment and the KV checkpoint is rewritten. Advances the
    /// database schema version but not <see cref="TableSchema.Version"/>. Cluster mode only —
    /// standalone goes through <see cref="SetTableCommentAsync"/>.
    ///
    /// <para><paramref name="comment"/> is null to remove the comment; the empty string stores a
    /// present-but-empty one.</para>
    /// </summary>
    /// <summary>Whether a non-materialized view with this name currently exists.</summary>
    public static bool ViewExists(DatabaseDescriptor database, string viewName)
        => database.Schema.Views.ContainsKey(viewName);

    /// <summary>
    /// Proposes a <see cref="SchemaOp.CreateView"/> (or <see cref="SchemaOp.ReplaceView"/>) delta and
    /// waits for it to apply locally. The view id is allocated by the caller and carried in the
    /// payload so every node assigns the same one.
    /// </summary>
    /// <remarks>
    /// The name-availability check runs <b>under the schema lock, here</b>, in the same critical
    /// section that builds the delta — not in the caller. Checking outside the lock would be a
    /// check-then-act that two concurrent creations both pass.
    /// </remarks>
    public async Task CreateViewAsync(
        DatabaseDescriptor database,
        string viewId,
        string viewName,
        ViewDefinition definition,
        string? comment,
        bool replace)
    {
        SchemaChangeLogEntry entry;

        await database.Schema.AcquireLockAsync().ConfigureAwait(false);
        try
        {
            if (replace)
            {
                if (!database.Schema.Views.ContainsKey(viewName))
                    throw new CamusDBException(
                        CamusDBErrorCodes.ViewDoesntExist,
                        $"View '{viewName}' does not exist");
            }
            else
            {
                database.Schema.RequireRelationNameAvailable(viewName);
            }

            entry = new()
            {
                Database = database.Id,
                FromVersion = database.Schema.SchemaVersion,
                ToVersion = database.Schema.SchemaVersion + 1,
                Op = replace ? SchemaOp.ReplaceView : SchemaOp.CreateView,
                Payload = Serializator.Serialize(new SchemaViewPayload
                {
                    ViewId = viewId,
                    ViewName = viewName,
                    Definition = definition,
                    Comment = comment
                })
            };
            SchemaDeltaApplier.ValidateSchemaDelta(database, entry);
        }
        finally
        {
            database.Schema.ReleaseLock();
        }

        await publisher.ReplicateAndWaitLocalApplyAsync(database, entry).ConfigureAwait(false);
    }

